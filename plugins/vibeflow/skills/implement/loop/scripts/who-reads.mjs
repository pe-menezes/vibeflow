#!/usr/bin/env node
// Who reads this file? Run it before putting a file in the anti-scope or telling a value to stay.
// Searches the repository (tests, scripts, generators, docs, CI) for the path and the name of
// each file the change touches, and says which references read the content. A spec that leaves
// a file out without asking who reads it hands the executor red tests it cannot fix.

import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

// The kit needs Node 18 or later (Node 16 has no global fetch): below it, say so and exit 64 first.
if (Number(process.versions.node.split('.')[0]) < 18) {
  process.stderr.write(`who-reads.mjs: needs Node.js 18 or later; found ${process.versions.node}\n`);
  process.exit(64);
}

const USAGE = `usage: who-reads.mjs <repo> <file>...

For each <file> (a path relative to the repository root), lists the tracked and untracked
files that mention its path or its name, and marks the ones that read it: a test, a script,
or a line that opens, imports or requires it. Says when the file itself is generated.

exit 0 nobody · 1 has readers · 64 bad arguments or not a git repository`;

const READ_TOKENS = ['readFileSync', 'readFile(', 'open(', 'read_text', 'cat ', 'fs.read', 'import ', 'require(', 'from ', 'source '];
const READER_FOLDERS = new Set(['test', 'tests', '__tests__', 'spec', 'scripts']);
const GENERATED_MARKS = ['generated by', 'auto-generated', '@generated', 'do not edit'];
const MAX_SHOWN = 40;

function fail(message) {
  console.error(`who-reads: ${message}`);
  process.exit(64);
}

function cleanEnv() {
  return Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')));
}

function git(dir, args, okStatuses = [0]) {
  const result = spawnSync('git', args, { cwd: dir, env: cleanEnv(), encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  if (result.error) fail(`git could not run: ${result.error.message}`);
  if (!okStatuses.includes(result.status)) fail(`git ${args[0]} failed: ${result.stderr.trim().slice(0, 200)}`);
  return result.stdout;
}

function references(top, target) {
  const name = basename(target);
  const patterns = [target, ...(name !== target && name.length > 6 ? [name] : [])];
  const args = ['grep', '-n', '-I', '-F', '--untracked'];
  for (const pattern of patterns) args.push('-e', pattern);
  args.push('--', '.', `:(exclude)${target}`, ':(exclude)package-lock.json', ':(exclude)*.lock');
  return git(top, args, [0, 1]).split('\n').filter((line) => line.trim());
}

function isReader(line) {
  const path = line.split(':', 1)[0];
  const segments = path.split('/');
  if (segments.slice(0, -1).some((segment) => READER_FOLDERS.has(segment))) return true;
  if (/\.(test|spec)\.[a-z]+$/.test(path)) return true;
  return READ_TOKENS.some((token) => line.includes(token));
}

function isGenerated(top, target) {
  try {
    const head = readFileSync(join(top, target), 'utf8').slice(0, 1500).toLowerCase();
    return GENERATED_MARKS.some((mark) => head.includes(mark));
  } catch {
    return false;
  }
}

function main(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(USAGE);
    return 0;
  }
  if (argv.length < 2) fail(`expected <repo> <file>...\n\n${USAGE}`);
  const [repo, ...targets] = argv;
  const top = git(resolve(repo), ['rev-parse', '--show-toplevel']).trim();
  let anyReader = false;
  for (const target of targets.map((path) => path.replace(/^\.\//, ''))) {
    const lines = references(top, target);
    const generated = isGenerated(top, target) ? ' · generated file: it changes only through its generator' : '';
    console.log(`== ${target}: ${lines.length} reference(s)${generated}`);
    // Tests and scripts first: they are the readers that turn red.
    const ordered = [...lines].sort((a, b) => Number(isReader(b)) - Number(isReader(a)));
    for (const line of ordered.slice(0, MAX_SHOWN)) {
      const reads = isReader(line);
      anyReader ||= reads;
      console.log(`  ${reads ? 'reads ' : '      '}${line.slice(0, 220)}`);
    }
    anyReader ||= ordered.slice(MAX_SHOWN).some(isReader);
    if (lines.length > MAX_SHOWN) console.log(`  ... ${lines.length - MAX_SHOWN} more (narrow with git grep)`);
  }
  if (anyReader) {
    console.log('\nA test, script or generator reads what the change touches: decide in the spec whether the part updates each one or the value stays, before dispatch.');
    return 1;
  }
  return 0;
}

process.exit(main(process.argv.slice(2)));
